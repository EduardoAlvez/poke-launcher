const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('launcher', {
  addSlot: (name, url) => ipcRenderer.invoke('launcher:add-slot', { name, url }),
  removeSlot: (id) => ipcRenderer.invoke('launcher:remove-slot', { id }),
  renameSlot: (id, name) => ipcRenderer.invoke('launcher:rename-slot', { id, name }),
  setLayout: (cols) => ipcRenderer.invoke('launcher:set-layout', { cols }),
  setToolbarCollapsed: (collapsed) => ipcRenderer.invoke('launcher:set-toolbar-collapsed', { collapsed: collapsed === true }),
  setFocusedSlot: (id) => ipcRenderer.invoke('launcher:set-focus', { id }),
  setLightMode: (id, on) => ipcRenderer.invoke('launcher:set-light', { id, on: on === true }),
  focusSlot: (id) => ipcRenderer.send('launcher:focus-slot', { id }),
  slotMenu: (id) => ipcRenderer.invoke('launcher:slot-menu', { id }),
  closePopups: () => ipcRenderer.invoke('launcher:close-popups'),
  runDiagnostics: () => ipcRenderer.invoke('diagnostics:collect'),
  setViewsVisible: (visible) => ipcRenderer.send('launcher:views-visible', visible === true),
  setAutomation: (id, config) => ipcRenderer.invoke('automation:set', { id, config }),
  stopAllAutomation: () => ipcRenderer.invoke('automation:stop-all'),
  riskText: () => ipcRenderer.invoke('automation:risk-text'),
  scripts: () => ipcRenderer.invoke('launcher:scripts'),
  saveScript: (script) => ipcRenderer.invoke('launcher:script-save', { script }),
  deleteScript: (id) => ipcRenderer.invoke('launcher:script-delete', { id }),
  runScripts: (id) => ipcRenderer.invoke('launcher:script-run', { id }),
  hunt: (id, opts) => ipcRenderer.invoke('launcher:hunt', { id, levelCap: opts?.levelCap === true }),
  dexSet: (id, on) => ipcRenderer.invoke('launcher:dex-set', { id, on: on === true }),
  routeSet: (opts) => ipcRenderer.invoke('launcher:route-set', opts),
  routeRisk: () => ipcRenderer.invoke('route:risk-text'),
  p2Set: (opts) => ipcRenderer.invoke('launcher:p2-set', opts),
  p2Risk: () => ipcRenderer.invoke('p2:risk-text'),
  setProxy: (id, proxy) => ipcRenderer.invoke('launcher:set-proxy', { id, proxy }),
  onState: (cb) => ipcRenderer.on('launcher:state', (_e, slots) => cb(slots)),
  onRenameRequest: (cb) => ipcRenderer.on('launcher:rename-request', (_e, payload) => cb(payload ?? {})),
  onProxyRequest: (cb) => ipcRenderer.on('launcher:proxy-request', (_e, payload) => cb(payload ?? {})),
});
